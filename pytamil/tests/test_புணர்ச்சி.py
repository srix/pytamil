# -*- coding: utf-8 -*-
"""புணர்ச்சி சோதனைகள்: நிலைமொழி + வருமொழி -> தொடர்மொழி, விதிக் கோப்பின் சான்றுகள் உட்பட."""
import pytest

from pytamil.தமிழ் import புணர்ச்சி


@pytest.mark.parametrize("நிலைமொழி, வருமொழி, தொடர்மொழி", [
    ('சே', 'அடி', ['சேயடி', 'சேவடி']),
])
def test_தொடர்மொழி_ஆக்கு(நிலைமொழி, வருமொழி, தொடர்மொழி):
    தொடர்மொழி_பதங்கள் = புணர்ச்சி.தொடர்மொழி_ஆக்கு(நிலைமொழி, வருமொழி)
    assert len(தொடர்மொழி_பதங்கள்) == len(தொடர்மொழி)

    for பதம் in தொடர்மொழி_பதங்கள்:
        assert பதம் in தொடர்மொழி


# ஒவ்வொரு சான்றும் ஒரு சோதனை (புணர்ச்சிவிதிகள்.yaml)
entries = புணர்ச்சி.load("pytamil/தமிழ்/resources/புணர்ச்சிவிதிகள்.yaml")
சான்றுகள் = புணர்ச்சி.getசான்றுகள்(entries, [])

params = [(சான்று.நிலைமொழி, சான்று.வருமொழி, சான்று.தொடர்மொழி) for சான்று in சான்றுகள்]


@pytest.mark.parametrize("நிலைமொழி, வருமொழி, தொடர்மொழி", params)
def test_சான்று_தொடர்மொழி_ஆக்கு(நிலைமொழி, வருமொழி, தொடர்மொழி):
    தொடர்மொழி_பதங்கள் = புணர்ச்சி.தொடர்மொழி_ஆக்கு(நிலைமொழி, வருமொழி)

    assert len(தொடர்மொழி_பதங்கள்) == len(தொடர்மொழி)

    for பதம் in தொடர்மொழி_பதங்கள்:
        assert பதம் in தொடர்மொழி
