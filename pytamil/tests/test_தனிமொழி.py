# -*- coding: utf-8 -*-
"""தனிமொழி_ஆக்கு: தொடர்மொழியைத் தனிமொழிகளாகப் பிரித்தல் — ஒவ்வொரு சான்றும் திரும்பப் பிரிய வேண்டும்."""
import pytest

from pytamil.தமிழ் import புணர்ச்சி

சான்றுகள் = புணர்ச்சி.getசான்றுகள்(புணர்ச்சி.load("pytamil/தமிழ்/resources/புணர்ச்சிவிதிகள்.yaml"), [])
params = [(தொ, ச.நிலைமொழி, ச.வருமொழி, ச.வகை) for ச in சான்றுகள் for தொ in ச.தொடர்மொழி]


@pytest.mark.parametrize("தொடர்மொழி, நிலைமொழி, வருமொழி, வகை", params)
def test_சான்று_திரும்பப்_பிரியும்(தொடர்மொழி, நிலைமொழி, வருமொழி, வகை):
    பிரிப்புகள் = புணர்ச்சி.தனிமொழி_ஆக்கு(தொடர்மொழி)
    assert any(பி.நிலைமொழி == நிலைமொழி and பி.வருமொழி == வருமொழி and (வகை is None or பி.வகை == வகை)
               for பி in பிரிப்புகள்), பிரிப்புகள்


def test_விருந்தோம்பல்():
    # README-இன் எடுத்துக்காட்டு
    பிரிப்புகள் = புணர்ச்சி.தனிமொழி_ஆக்கு('விருந்தோம்பல்')
    assert ('விருந்து', 'ஓம்பல்') in [(பி.நிலைமொழி, பி.வருமொழி) for பி in பிரிப்புகள்]


def test_பிரிப்பு_முன்னோக்கிச்_சரி():
    # திரும்பும் ஒவ்வொரு பிரிப்பும் முன்னோக்கிச் சேர்த்தால் அத்தொடர்மொழியே வர வேண்டும்
    for தொ in ['மணியடித்தான்', 'மட்குடம்', 'மரக்கிளை', 'தங்கை', 'மெய்யெழுத்து']:
        for பி in புணர்ச்சி.தனிமொழி_ஆக்கு(தொ):
            assert தொ in புணர்ச்சி.தொடர்மொழி_ஆக்கு(பி.நிலைமொழி, பி.வருமொழி, பி.வகை), (தொ, பி)


def test_பிரிக்க_இயலாதது():
    assert புணர்ச்சி.தனிமொழி_ஆக்கு('கடல்') == []     # ஒரு சொல்; எந்த விதியும் உருவாக்காது
    assert புணர்ச்சி.தனிமொழி_ஆக்கு('') == []


def test_வரிசை_எளியது_முதல்():
    # மாற்றம் குறைந்த பிரிப்பு முன்னே: சேயடி -> (சேய், அடி) இயல்பு [0 மாற்றம்] முன், (சே, அடி) உடம்படுமெய் பின்
    பிரிப்புகள் = புணர்ச்சி.தனிமொழி_ஆக்கு('சேயடி')
    ஜோடிகள் = [(பி.நிலைமொழி, பி.வருமொழி) for பி in பிரிப்புகள்]
    assert ('சே', 'அடி') in ஜோடிகள் and ('சேய்', 'அடி') in ஜோடிகள்
    assert ஜோடிகள்.index(('சேய்', 'அடி')) < ஜோடிகள்.index(('சே', 'அடி'))
