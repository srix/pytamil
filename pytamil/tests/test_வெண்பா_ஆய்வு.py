குறள்_467 = "எண்ணித் துணிகக் கருமம் துணிந்தபின்\nஎண்ணுவ மென்பதி ழுக்கு"

நளவெண்பா_1 = """ஆதித் தனிக்கோல மானா னடியவற்காச்
சோதித் திருத்தூணிற் றோன்றினான் வேதத்தின்
முன்னின்றான் வேழம் முதலே யெனவழைப்ப
என்னென்றா னெங்கட் கிறை"""

குறுந்தொகை_3 = """நிலத்தினும் பெரிதே வானினும் உயர்ந்தன்று
நீரினும் ஆரள வின்றே சாரல்
கருங்கோல் குறிஞ்சிப் பூக்கொண்டு
பெருந்தேன் இழைக்கும் நாடனொடு நட்பே"""


def விதிகள்(முடிவு):
    return [ப.விதி for ப in முடிவு.பிழைகள்]


# ---------- சரியான வெண்பாக்கள் ----------

def test_குறள்_467():
    மு = வெண்பா.ஆய்வு(குறள்_467)
    assert மு.சரியா, மு.பிழைகள்
    assert மு.வகை == 'குறள்_வெண்பா'
    assert மு.வாய்பாடுகள்() == [['தேமா', 'புளிமா', 'புளிமா', 'கருவிளம்'], ['கூவிளம்', 'கூவிளம்', 'காசு']]
    assert len(மு.தளைகள்) == 6                       # 3 + 1 (அடி இணைப்பு) + 2
    assert all(த.வெண்டளையா for த in மு.தளைகள்)
    assert [த.தளை for த in மு.தளைகள்][-1] == 'இயற்சீர்_வெண்டளை'   # கூவிளம் -> காசு: விளமுன் நேர்


def test_குறள்_467_அசைகள்():
    மு = வெண்பா.ஆய்வு(குறள்_467)
    ஈற்றடி = மு.அடிகள்[1]
    assert [(ச.பதம், ச.அசைகள்) for ச in ஈற்றடி] == [
        ('எண்ணுவ', ['நேர்', 'நிரை']), ('மென்பதி', ['நேர்', 'நிரை']), ('ழுக்கு', ['நேர்', 'நேர்'])]


