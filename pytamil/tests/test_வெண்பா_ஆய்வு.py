# ---------- விதி மீறல்கள் ----------

def test_வெண்டளை_பிழை():
    # துணிகக் (புளிமா) -> தானே (தேமா): மாமுன் நேர் = நேரொன்றாசிரியத்தளை
    மு = வெண்பா.ஆய்வு("எண்ணித் தானே கருமம் துணிந்தபின்\nஎண்ணுவ மென்பதி ழுக்கு")
    assert not மு.சரியா
    பி = [ப for ப in மு.பிழைகள் if ப.விதி == 'வெண்டளை_பிழை']
    assert [(ப.அடி, ப.சீர்) for ப in பி] == [(1, 1)]
    assert 'நேரொன்றாசிரியத்தளை' in பி[0].விவரம்
    assert len(மு.பிழைகள்) == 1                       # வேறு எதுவும் தவறில்லை


def test_ஈற்றுச்சீர்_பிழை():
    # ழுக்குதல் = ழுக்/குதல் = நேர் நிரை = கூவிளம்; நாள்/மலர்/காசு/பிறப்பு அன்று
    மு = வெண்பா.ஆய்வு("எண்ணித் துணிகக் கருமம் துணிந்தபின்\nஎண்ணுவ மென்பதி ழுக்குதல்")
    assert 'ஈற்றுச்சீர்_பிழை' in விதிகள்(மு)
    பி = next(ப for ப in மு.பிழைகள் if ப.விதி == 'ஈற்றுச்சீர்_பிழை')
    assert (பி.அடி, பி.சீர்) == (2, 3) and 'கூவிளம்' in பி.விவரம்


