@pytest.mark.parametrize("அடிகள், வகை", [
    (2, 'குறள்_வெண்பா'), (3, 'சிந்தியல்_வெண்பா'), (4, 'நேரிசை_வெண்பா'), (5, 'பஃறொடை_வெண்பா'),
    (12, 'பஃறொடை_வெண்பா'), (13, 'கலி_வெண்பா'),
])
def test_வகை_அடி_எண்ணிக்கையால்(அடிகள், வகை):
    # முதல் அடியை மீண்டும் மீண்டும் வைத்து; தளை/சீர் சரியெனத் தேவையில்லை, வகை மட்டும் பார்க்கிறோம்
    பாடல் = "\n".join(["எண்ணித் துணிகக் கருமம் துணிந்தபின்"] * (அடிகள் - 1) + ["எண்ணுவ மென்பதி ழுக்கு"])
    assert வெண்பா.ஆய்வு(பாடல்).வகை == வகை


def test_கனிச்சீர்_தடை():
    # தண்ணீர்குடம் = தண்/ணீர்/குடம் = நேர் நேர் நிரை = தேமாங்கனி; காய் ஆகப் பிரிக்க இயலாது
    மு = வெண்பா.ஆய்வு("எண்ணித் தண்ணீர்குடம் கருமம் துணிந்தபின்\nஎண்ணுவ மென்பதி ழுக்கு")
    assert மு.வாய்பாடுகள்()[0][1] == 'தேமாங்கனி'
    பி = next(ப for ப in மு.பிழைகள் if ப.விதி == 'கனிச்சீர்_தடை')
    assert (பி.அடி, பி.சீர்) == (1, 2)
    # கனிமுன் நிரை (கருமம்) = ஒன்றிய வஞ்சித்தளை -> வெண்டளை_பிழையும் வரும்
    assert any('வஞ்சித்தளை' in ப.விவரம் for ப in மு.பிழைகள் if ப.விதி == 'வெண்டளை_பிழை')


def test_நாலசைச்சீர்_தடை():
    # குறள் 13 சொற்பிரிப்பில்: வியனுலகத்து = விய/னுல/கத்/து = நிரை நிரை நேர் நேர் = கருவிளந்தண்பூ
    மு = வெண்பா.ஆய்வு("விண்இன்று பொய்ப்பின் விரிநீர் வியனுலகத்து\nஉள்நின்று உடற்றும் பசி")
    assert மு.வகை == 'குறள்_வெண்பா'                       # முழுப் பாடலும் பாகுபட்டது
    assert மு.வாய்பாடுகள்()[0][3] == 'கருவிளந்தண்பூ'
    பி = next(ப for ப in மு.பிழைகள் if ப.விதி == 'நாலசைச்சீர்_தடை')
    assert (பி.அடி, பி.சீர்) == (1, 4)
    assert not any(ப.விதி == 'பாகுபாட்டுப்பிழை' for ப in மு.பிழைகள்)
