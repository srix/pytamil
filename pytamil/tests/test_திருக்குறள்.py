# -*- coding: utf-8 -*-
import csv
import pytest
from pytamil import திருக்குறள்


def test_குறள்_உரை():
    assert திருக்குறள்.குறள்_உரை(467) == "எண்ணித் துணிக கருமம் துணிந்தபின்\nஎண்ணுவம் என்பது இழுக்கு"
    assert திருக்குறள்.குறள்_உரை(1).startswith("அகர முதல")


def test_குறள்கள்_மேல்தகவல்():
    கு = next(திருக்குறள்.குறள்கள்([1]))
    assert கு['எண்'] == 1 and கு['பால்'] and கு['அதிகாரம்'] and "\n" in கு['உரை']


def test_வெண்பா_ஆய்வு_வரிசை():
    வரிகள் = list(திருக்குறள்.வெண்பா_ஆய்வு_வரிசை([1, 467]))
    assert [வ['எண்'] for வ in வரிகள்] == [1, 467]
    assert வரிகள்[0]['வகை'] == 'குறள்_வெண்பா' and வரிகள்[0]['சரியா'] == 'ஆம்'
    assert வரிகள்[0]['சீர்கள்'] == 'புளிமா புளிமா புளிமாங்காய் தேமா / புளிமா புளிமா பிறப்பு'
    # 467 சொற்பிரிப்பில்: என்பது -> இழுக்கு விளமுன் நிரை (சந்திப் பிரிப்புச் சிக்கல், கருவி குறிப்பில் உள்ளது)
    assert வரிகள்[1]['சரியா'] == 'இல்லை' and 'வெண்டளை_பிழை[2:2]' in வரிகள்[1]['பிழைகள்']


def test_வெண்பா_ஆய்வு_csv(tmp_path):
    கோப்பு = tmp_path / "வெண்பா.csv"
    தொகுப்பு = திருக்குறள்.வெண்பா_ஆய்வு_csv(str(கோப்பு), [1, 2, 3])
    assert தொகுப்பு['மொத்தம்'] == 3 and 0 <= தொகுப்பு['சரி'] <= 3
    with open(கோப்பு, encoding='utf8') as f:
        வரிகள் = list(csv.DictReader(f))
    assert len(வரிகள்) == 3 and list(வரிகள்[0].keys()) == திருக்குறள்.வெண்பா_நெடுவரிசைகள்
    உரை = திருக்குறள்.தொகுப்பு_உரை(தொகுப்பு)
    assert "குறள்கள்: 3" in உரை


def test_எண்கள்():
    assert திருக்குறள்._எண்கள்("1-3,467") == [1, 2, 3, 467] and திருக்குறள்._எண்கள்(None) is None


def test_main_வெண்பா(tmp_path, capsys):
    out = tmp_path / "o.csv"
    assert திருக்குறள்.main(['வெண்பா', '--எண்கள்', '1-2', '--வெளியீடு', str(out)]) == 0
    assert "குறள்கள்: 2" in capsys.readouterr().out and out.exists()
