# YAML-இல் இன்னும் # குறியிட்டுள்ள விதிகள்: இலக்கணம் இவற்றையும் ஏற்க வேண்டும்
வரவிருக்கும்_விதிகள் = [
    "(...)('ண்') +வேற்றுமை+ (வல்லினம்)(...) = நிலைமொழி|திரிதல்('ட்').வருமொழி",
    "(...)('ன்') +வேற்றுமை+ (வல்லினம்)(...) = நிலைமொழி|திரிதல்('ற்').வருமொழி",
    "(...)('ண்','ன்') +வேற்றுமை+ (மெல்லினம்,இடையினம்)(...) = நிலைமொழி +இயல்பு+ வருமொழி",
    "(...)('ண்','ன்') +அல்வழி+ (வல்லினம்,மெல்லினம்,இடையினம்)(...) = நிலைமொழி +இயல்பு+ வருமொழி",
    "(தனிக்குறில்)(மெய்) + (உயிர்)(...) = நிலைமொழி|இரட்டுதல் + வருமொழி",
]


# சோதனைகளில் பயன்படும் விதி வரிகள் (புணர்ச்சிவிதிகள்.yaml-இல் உள்ளவாறே)
ஏமுன்_யவ = "(...)(ஏ) + (உயிர்)(...) = நிலைமொழி|உடம்படுமெய்(ய்) + வருமொழி , நிலைமொழி|உடம்படுமெய்(வ்) + வருமொழி"
இருபுற_வடிகட்டி = "(...)(ஏ) + (உயிர்)(...) = நிலைமொழி|உடம்படுமெய்(ய்)|சும்மா + சும்மா|திரிதல்(வ்)|வருமொழி"


@pytest.mark.parametrize("வரி, நிலைமொழி_regex, வருமொழி_regex", [
    ("(...)(இ,ஈ,ஐ) + (உயிர்)(...) = நிலைமொழி|உடம்படுமெய்(ய்) + வருமொழி",
     ".*(இ|ஈ|ஐ)", "(அ|ஆ|இ|ஈ|உ|ஊ|எ|ஏ|ஐ|ஒ|ஓ|ஔ).*"),
    ("(...)(மெய்) + (உயிர்)(...) = நிலைமொழி +இயல்பு+ வருமொழி",
     ".*(க்|ச்|ட்|த்|ப்|ற்|ஞ்|ங்|ண்|ந்|ம்|ன்|ய்|ர்|ல்|வ்|ழ்|ள்)", "(அ|ஆ|இ|ஈ|உ|ஊ|எ|ஏ|ஐ|ஒ|ஓ|ஔ).*"),
    ("(தனிக்குறில்)(மெய்) + (உயிர்)(...) = நிலைமொழி|இரட்டுதல் + வருமொழி",
     "..(அ|இ|உ|எ|ஒ)(க்|ச்|ட்|த்|ப்|ற்|ஞ்|ங்|ண்|ந்|ம்|ன்|ய்|ர்|ல்|வ்|ழ்|ள்)", "(அ|ஆ|இ|ஈ|உ|ஊ|எ|ஏ|ஐ|ஒ|ஓ|ஔ).*"),
])
def test_இடப்பக்கம்_regex(வரி, நிலைமொழி_regex, வருமொழி_regex):
    விதி = புணர்ச்சி.விதி_ஆக்கு(வரி)
    assert (விதி.நிலைமொழி_regex, விதி.வருமொழி_regex) == (நிலைமொழி_regex, வருமொழி_regex)


