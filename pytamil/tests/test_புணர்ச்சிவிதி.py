"""புணர்ச்சி விதி வரிகளின் பாகுபாடும் செயற்படுத்தலும் (resources/புணர்ச்சிவிதிகள்.g4)."""
import pytest

from pytamil.தமிழ் import புணர்ச்சி

# YAML-இல் இன்னும் # குறியிட்டுள்ள விதிகள்: இலக்கணம் இவற்றையும் ஏற்க வேண்டும்
வரவிருக்கும்_விதிகள் = [
    "(...)('ண்') +வேற்றுமை+ (வல்லினம்)(...) = நிலைமொழி|திரிதல்('ட்').வருமொழி",
    "(...)('ன்') +வேற்றுமை+ (வல்லினம்)(...) = நிலைமொழி|திரிதல்('ற்').வருமொழி",
    "(...)('ண்','ன்') +வேற்றுமை+ (மெல்லினம்,இடையினம்)(...) = நிலைமொழி +இயல்பு+ வருமொழி",
    "(...)('ண்','ன்') +அல்வழி+ (வல்லினம்,மெல்லினம்,இடையினம்)(...) = நிலைமொழி +இயல்பு+ வருமொழி",
    "(தனிக்குறில்)(மெய்) + (உயிர்)(...) = நிலைமொழி|இரட்டுதல் + வருமொழி",
]


@pytest.mark.parametrize("வரி, நிலைமொழி_regex, வருமொழி_regex", [
    ("(...)(இ,ஈ,ஐ) + (உயிர்)(...) = நிலைமொழி|உடம்படுமெய்(ய்) + வருமொழி",
     ".*(இ|ஈ|ஐ)", "(அ|ஆ|இ|ஈ|உ|ஊ|எ|ஏ|ஐ|ஒ|ஓ|ஔ).*"),
    ("(...)(மெய்) + (உயிர்)(...) = நிலைமொழி +இயல்பு+ வருமொழி",
     ".*(க்|ச்|ட்|த்|ப்|ற்|ஞ்|ங்|ண்|ந்|ம்|ன்|ய்|ர்|ல்|வ்|ழ்|ள்)", "(அ|ஆ|இ|ஈ|உ|ஊ|எ|ஏ|ஐ|ஒ|ஓ|ஔ).*"),
    ("(தனிக்குறில்)(மெய்) + (உயிர்)(...) = நிலைமொழி|இரட்டுதல் + வருமொழி",
     "..(அ|இ|உ|எ|ஒ)(க்|ச்|ட்|த்|ப்|ற்|ஞ்|ங்|ண்|ந்|ம்|ன்|ய்|ர்|ல்|வ்|ழ்|ள்)", "(அ|ஆ|இ|ஈ|உ|ஊ|எ|ஏ|ஐ|ஒ|ஓ|ஔ).*"),
])
def test_இடப்பக்கம்_regex(வரி, நிலைமொழி_regex, வருமொழி_regex):
    விதி = புணர்ச்சி.விதி_ஆக்கு(வரி)
    assert (விதி.நிலைமொழி_regex, விதி.வருமொழி_regex) == (நிலைமொழி_regex, வருமொழி_regex)


def test_ஏற்றிய_விதிகள்():
    assert len(புணர்ச்சி.விதிகள்) == 4 and all(வ.வகை == 'பொது' for வ in புணர்ச்சி.விதிகள்)


@pytest.mark.parametrize("வரி", வரவிருக்கும்_விதிகள்)
def test_வரவிருக்கும்_விதிகள்_பாகுபடும்(வரி):
    assert புணர்ச்சி.விதி_ஆக்கு(வரி).மாற்றங்கள்


def test_விதிப்_பகுதிகள்():
    விதி = புணர்ச்சி.விதி_ஆக்கு("(...)('ண்') +வேற்றுமை+ (வல்லினம்)(...) = நிலைமொழி|திரிதல்('ட்').வருமொழி")
    assert விதி.வகை == 'வேற்றுமை'
    assert விதி.நிலைமொழி_regex == ".*(ண்)" and விதி.வருமொழி_regex == "(க்|ச்|ட்|த்|ப்|ற்).*"
    [மா] = விதி.மாற்றங்கள்
    assert மா.நிலைமொழி_வடிகட்டிகள் == [புணர்ச்சி.வடிகட்டி('திரிதல்', 'ட்')]
    assert மா.இணைப்பு == '.' and மா.வருமொழி_வடிகட்டிகள் == []
    assert புணர்ச்சி.செயற்படுத்து(விதி, 'மண்', 'குடம்') == ['மட்குடம்']


def test_பல_மாற்றங்கள்():
    விதி = புணர்ச்சி.விதி_ஆக்கு("(...)(ஏ) + (உயிர்)(...) = நிலைமொழி|உடம்படுமெய்(ய்) + வருமொழி , நிலைமொழி|உடம்படுமெய்(வ்) + வருமொழி")
    assert புணர்ச்சி.செயற்படுத்து(விதி, 'சே', 'அடி') == ['சேய்+அடி', 'சேவ்+அடி']


def test_இருபுற_வடிகட்டிகள்_வரிசை():
    # வருமொழிப் பக்கத்தில் 'வருமொழி'க்கு அண்மையானது முதலில் செயற்பட வேண்டும்
    விதி = புணர்ச்சி.விதி_ஆக்கு("(...)(ஏ) + (உயிர்)(...) = நிலைமொழி|உடம்படுமெய்(ய்)|சும்மா + சும்மா|திரிதல்(வ்)|வருமொழி")
    assert புணர்ச்சி.செயற்படுத்து(விதி, 'சே', 'அடி') == ['சேய்+அவ்']


def test_தவறான_விதி_பிழை():
    with pytest.raises(புணர்ச்சி.புணர்ச்சிவிதிப்பிழை):
        புணர்ச்சி.விதி_ஆக்கு("(...)(ஏ) = நிலைமொழி வருமொழி")


def test_வகை_வடிகட்டல்():
    # YAML-இல் வேற்றுமை விதிகள் இன்னும் இல்லை; வகை கொடுத்தாலும் பொது விதிகள் மட்டும் பொருந்தும்
    assert புணர்ச்சி.தொடர்மொழி_ஆக்கு('மண்', 'குடம்') == []
    assert புணர்ச்சி.தொடர்மொழி_ஆக்கு('மண்', 'குடம்', வகை='வேற்றுமை') == []
    assert புணர்ச்சி.தொடர்மொழி_ஆக்கு('சே', 'அடி', வகை='அல்வழி') == ['சேயடி', 'சேவடி']


@pytest.mark.parametrize("பதம், புது, எதிர்பார்ப்பு", [
    ('சே', 'ய்', 'சேய்'), ('நிலா', 'வ்', 'நிலாவ்'),
])
def test_உடம்படுமெய்(பதம், புது, எதிர்பார்ப்பு):
    assert புணர்ச்சி.உடம்படுமெய்(பதம், புது) == எதிர்பார்ப்பு


def test_திரிதல்_இரட்டுதல்():
    assert புணர்ச்சி.திரிதல்('மண்', 'ட்') == 'மட்' and புணர்ச்சி.திரிதல்('பொன்', 'ற்') == 'பொற்'
    assert புணர்ச்சி.இரட்டுதல்('கல்') == 'கல்ல்'
