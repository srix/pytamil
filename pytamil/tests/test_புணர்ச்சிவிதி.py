def test_வகை_வடிகட்டல்():
    # வகை கொடுக்காவிடின் பொது விதிகள் மட்டும்; வேற்றுமை/அல்வழி கொடுத்தால் அவ்வகை விதிகளும்
    assert புணர்ச்சி.தொடர்மொழி_ஆக்கு('மண்', 'குடம்') == []
    assert புணர்ச்சி.தொடர்மொழி_ஆக்கு('மண்', 'குடம்', வகை='வேற்றுமை') == ['மட்குடம்']
    assert புணர்ச்சி.தொடர்மொழி_ஆக்கு('மண்', 'சரிந்தது', வகை='அல்வழி') == ['மண்சரிந்தது']
    assert புணர்ச்சி.தொடர்மொழி_ஆக்கு('சே', 'அடி', வகை='அல்வழி') == ['சேயடி', 'சேவடி']


# சிறப்புவிதி பொதுவிதியை மறைக்கும்
@pytest.mark.parametrize("நிலைமொழி, வகை, வருமொழி, எதிர்பார்ப்பு", [
    ('மெய்', None, 'எழுத்து', ['மெய்யெழுத்து']),          # தனிக்குறில் இரட்டுதல் > மெய்+உயிர் இயல்பு
    ('உயிர்', None, 'எழுத்து', ['உயிரெழுத்து']),          # பொதுவிதி மட்டும் பொருந்தும்
    ('விருந்து', None, 'ஓம்பல்', ['விருந்தோம்பல்']),      # குற்றியலுகரம் > உ-ஈறு உடம்படுமெய்
    ('பசு', None, 'இனம்', ['பசுவினம்']),                  # முற்றியலுகரம்: குற்றியலுகர விதி பொருந்தாது
    ('மீன்', 'வேற்றுமை', 'குழம்பு', ['மீன்குழம்பு']),      # ('மீன்') > (...)('ன்') திரிதல்
    ('பொன்', 'வேற்றுமை', 'குடம்', ['பொற்குடம்']),
    ('தம்', None, 'கை', ['தங்கை']),                        # (நும்,தம்,எம்,நம்) > (...)('ம்')
    ('மரம்', 'வேற்றுமை', 'கிளை', ['மரக்கிளை']),
])
def test_சிறப்புவிதி_முன்னுரிமை(நிலைமொழி, வகை, வருமொழி, எதிர்பார்ப்பு):
    assert புணர்ச்சி.தொடர்மொழி_ஆக்கு(நிலைமொழி, வருமொழி, வகை) == எதிர்பார்ப்பு


def test_சிறப்பு_மதிப்பு():
    பொது = புணர்ச்சி.விதி_ஆக்கு("(...)(மெய்) + (உயிர்)(...) = நிலைமொழி +இயல்பு+ வருமொழி")
    சிறப்பு = புணர்ச்சி.விதி_ஆக்கு("(தனிக்குறில்)(மெய்) + (உயிர்)(...) = நிலைமொழி|இரட்டுதல் + வருமொழி")
    சொல் = புணர்ச்சி.விதி_ஆக்கு("('மீன்') +வேற்றுமை+ (வல்லினம்)(...) = நிலைமொழி +இயல்பு+ வருமொழி")
    எழுத்து = புணர்ச்சி.விதி_ஆக்கு("(...)('ன்') +வேற்றுமை+ (வல்லினம்)(...) = நிலைமொழி|திரிதல்('ற்').வருமொழி")
    assert சிறப்பு.சிறப்பு > பொது.சிறப்பு and சொல்.சிறப்பு > எழுத்து.சிறப்பு


def test_பட்டியலில்_வகைப்பெயர்_விரியும்():
    விதி = புணர்ச்சி.விதி_ஆக்கு("(...)('ண்','ன்') +வேற்றுமை+ (மெல்லினம்,இடையினம்)(...) = நிலைமொழி +இயல்பு+ வருமொழி")
    assert விதி.வருமொழி_regex == "(ங்|ஞ்|ண்|ந்|ம்|ன்|ய்|ர்|ல்|வ்|ழ்|ள்).*"


