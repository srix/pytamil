def test_விதிப்_பகுதிகள்():
    விதி = புணர்ச்சி.விதி_ஆக்கு("(...)('ண்') +வேற்றுமை+ (வல்லினம்)(...) = நிலைமொழி|திரிதல்('ட்').வருமொழி")
    assert விதி.வகை == 'வேற்றுமை'
    assert விதி.நிலைமொழி_regex == ".*(ண்)" and விதி.வருமொழி_regex == "(க்|ச்|ட்|த்|ப்|ற்).*"
    [மா] = விதி.மாற்றங்கள்
    assert மா.நிலைமொழி_வடிகட்டிகள் == [புணர்ச்சி.வடிகட்டி('திரிதல்', 'ட்')]
    assert மா.இணைப்பு == '.' and மா.வருமொழி_வடிகட்டிகள் == []
    assert புணர்ச்சி.செயற்படுத்து(விதி, 'மண்', 'குடம்') == ['மட்குடம்']


