"""சீர் கூறின் சோதனைகள்: ஒரு பதத்தின் சீர் வாய்பாட்டை (தேமா, கூவிளம் ...) அறிதல்."""
import pytest
from pytamil.தமிழ் import சீர்



@pytest.mark.parametrize("பதம்", [
        ("வானினும்"),
        ("நீரினும்"),
        ("தண்மையும்"),
        ("வெம்மையும்"),
        ("கையினை"),      # சீர்முதல் ஐ நெடில்: கை/யினை; புளிமா ஆகக் கூடாது
    ])
def test_கூவிளம்(பதம்):
    புது_சீர்_வாய்பாடு = சீர்.சீர்_வாய்பாடு_கொடு(பதம்)

    assert "கூவிளம்" == புது_சீர்_வாய்பாடு



@pytest.mark.parametrize("பதம்", [
        ("உயர்ந்தன்று"),
    ])
def test_புளிமாங்காய்(பதம்):
    புது_சீர்_வாய்பாடு = சீர்.சீர்_வாய்பாடு_கொடு(பதம்)

    assert "புளிமாங்காய்" == புது_சீர்_வாய்பாடு


@pytest.mark.parametrize("பதம்", [
    ("கேண்மை"),
    ("கையும்"),       # சீர்முதல் ஐ நெடிலாகவே நிற்கும்
    ("மையும்"),
    ("ஔவை"),         # ஔ (U+0B94) முன்பு பிரிக்கவே இயலாதிருந்தது ('ஒள' எழுத்துப்பிழை)
])
def test_தேமா(பதம்):
    assert "தேமா" == சீர்.சீர்_வாய்பாடு_கொடு(பதம்)


@pytest.mark.parametrize("பதம்", [
    ("தலைவன்"),
    ("ஒளியும்"),      # ஒளி/யும்; ஔ பிழை மீண்டும் வராமல் காக்கிறது
    ("அகர"),
])
def test_புளிமா(பதம்):
    assert "புளிமா" == சீர்.சீர்_வாய்பாடு_கொடு(பதம்)


@pytest.mark.parametrize("பதம்", [
    ("வழிபடுக"),      # காய் முன் கனி பின்: வழி/படு/க; புளிமாங்கனி அன்று
    ("னடியவற்காச்"),
])
def test_கருவிளங்காய்(பதம்):
    assert "கருவிளங்காய்" == சீர்.சீர்_வாய்பாடு_கொடு(பதம்)
