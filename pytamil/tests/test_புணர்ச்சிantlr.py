def _தொடர்மொழி_ஆக்கு_antlr(நிலைமொழி, வருமொழி):
    """TatSu இல்லாத தொடர்மொழி_ஆக்கு — புணர்ச்சி.py-இன் இணைப்புச் சுழற்சியை ANTLR விதிகளோடு."""
    import regex
    விதிகள் = [புணர்ச்சிantlr.விதி_ஆக்கு(வ) for வ in விதி_வரிகள்]
    நிவிரி, வவிரி = புணர்ச்சி.எழுத்து.உயிர்மெய்விரி(நிலைமொழி), புணர்ச்சி.எழுத்து.உயிர்மெய்விரி(வருமொழி)
    பதங்கள் = []
    for விதி in விதிகள்:
        if regex.fullmatch(விதி.நிலைமொழி_regex, நிவிரி) and regex.fullmatch(விதி.வருமொழி_regex, வவிரி):
            பதங்கள் += புணர்ச்சிantlr.செயற்படுத்து(விதி, நிலைமொழி, வருமொழி)
    முடிவு = []
    for ப in பதங்கள்:
        if '+' in ப:
            நி, வ = ப.split('+', 1); முடிவு += _தொடர்மொழி_ஆக்கு_antlr(நி, வ)
        else:
            முடிவு.append(ப)
    return முடிவு


