விதி_வரிகள் = [வ.வாக்கியம் for வ in புணர்ச்சி.விதிகள்]

# YAML-இல் இன்னும் # குறியிட்டுள்ள விதிகள்: இலக்கணம் இவற்றையும் ஏற்க வேண்டும்
வரவிருக்கும்_விதிகள் = [
    "(...)('ண்') +வேற்றுமை+ (வல்லினம்)(...) = நிலைமொழி|திரிதல்('ட்').வருமொழி",
    "(...)('ன்') +வேற்றுமை+ (வல்லினம்)(...) = நிலைமொழி|திரிதல்('ற்').வருமொழி",
    "(...)('ண்','ன்') +வேற்றுமை+ (மெல்லினம்,இடையினம்)(...) = நிலைமொழி +இயல்பு+ வருமொழி",
    "(...)('ண்','ன்') +அல்வழி+ (வல்லினம்,மெல்லினம்,இடையினம்)(...) = நிலைமொழி +இயல்பு+ வருமொழி",
    "(தனிக்குறில்)(மெய்) + (உயிர்)(...) = நிலைமொழி|இரட்டுதல் + வருமொழி",
]


@pytest.mark.parametrize("வரி", விதி_வரிகள்)
def test_விதி_regex_ஒத்திருக்கிறது(வரி):
    பழையது = புணர்ச்சி.புணர்ச்சிவிதி(வரி)
    புதியது = புணர்ச்சிantlr.விதி_ஆக்கு(வரி)
    assert புதியது.நிலைமொழி_regex == பழையது.நிலைமொழி_regex
    assert புதியது.வருமொழி_regex == பழையது.வருமொழி_regex
    assert புதியது.வகை == 'பொது'


