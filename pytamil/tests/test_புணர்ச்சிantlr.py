def test_விதிப்_பகுதிகள்():
    விதி = புணர்ச்சிantlr.விதி_ஆக்கு("(...)('ண்') +வேற்றுமை+ (வல்லினம்)(...) = நிலைமொழி|திரிதல்('ட்').வருமொழி")
    assert விதி.வகை == 'வேற்றுமை'
    assert விதி.நிலைமொழி_regex == ".*(ண்)"
    assert விதி.வருமொழி_regex == "(க்|ச்|ட்|த்|ப்|ற்).*"
    [மா] = விதி.மாற்றங்கள்
    assert மா.நிலைமொழி_வடிகட்டிகள் == [புணர்ச்சிantlr.வடிகட்டி('திரிதல்', 'ட்')]
    assert மா.இணைப்பு == '.' and மா.வருமொழி_வடிகட்டிகள் == []
    assert புணர்ச்சிantlr.செயற்படுத்து(விதி, 'மண்', 'குடம்') == ['மட்குடம்']


def test_இருபுற_வடிகட்டிகள்_வரிசை():
    # வருமொழிப் பக்கத்தில் 'வருமொழி'க்கு அண்மையானது முதலில் செயற்பட வேண்டும்
    விதி = புணர்ச்சிantlr.விதி_ஆக்கு("(...)(ஏ) + (உயிர்)(...) = நிலைமொழி|உடம்படுமெய்(ய்)|சும்மா + சும்மா|திரிதல்(வ்)|வருமொழி")
    assert புணர்ச்சிantlr.செயற்படுத்து(விதி, 'சே', 'அடி') == ['சேய்+அவ்']


