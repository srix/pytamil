# -*- coding: utf-8 -*-
import pytest
from pytamil.தமிழ் import தளை


# எட்டு தளைகள்: முன்சீரின் வகை (மா/விளம்/காய்/கனி) + பின்சீரின் முதலசை (நேர்/நிரை)
@pytest.mark.parametrize("முன்சீர், பின்சீர், எதிர்பார்ப்பு", [
    # மாமுன் நிரை -> இயற்சீர் வெண்டளை ; மாமுன் நேர் -> நேரொன்று ஆசிரியத்தளை
    ("தேமா",        "புளிமா",       "இயற்சீர்_வெண்டளை"),
    ("புளிமா",      "கருவிளம்",     "இயற்சீர்_வெண்டளை"),
    ("தேமா",        "தேமா",         "நேரொன்றாசிரியத்தளை"),
    ("புளிமா",      "கூவிளம்",      "நேரொன்றாசிரியத்தளை"),
    # விளமுன் நேர் -> இயற்சீர் வெண்டளை ; விளமுன் நிரை -> நிரையொன்று ஆசிரியத்தளை
    ("கூவிளம்",     "தேமா",         "இயற்சீர்_வெண்டளை"),
    ("கருவிளம்",    "கூவிளங்காய்",  "இயற்சீர்_வெண்டளை"),
    ("கூவிளம்",     "புளிமா",       "நிரையொன்றாசிரியத்தளை"),
    ("கருவிளம்",    "கருவிளம்",     "நிரையொன்றாசிரியத்தளை"),
    # காய்முன் நேர் -> வெண்சீர் வெண்டளை ; காய்முன் நிரை -> கலித்தளை
    ("தேமாங்காய்",  "தேமா",         "வெண்சீர்_வெண்டளை"),
    ("புளிமாங்காய்", "கூவிளம்",     "வெண்சீர்_வெண்டளை"),
    ("கருவிளங்காய்", "புளிமா",      "கலித்தளை"),
    ("கூவிளங்காய்", "கருவிளம்",     "கலித்தளை"),
    # கனிமுன் நிரை -> ஒன்றிய வஞ்சித்தளை ; கனிமுன் நேர் -> ஒன்றாத வஞ்சித்தளை
    ("தேமாங்கனி",   "புளிமா",       "ஒன்றிய_வஞ்சித்தளை"),
    ("கூவிளங்கனி",  "கருவிளங்காய்", "ஒன்றிய_வஞ்சித்தளை"),
    ("புளிமாங்கனி", "தேமா",         "ஒன்றாத_வஞ்சித்தளை"),
    ("கருவிளங்கனி", "கூவிளம்",      "ஒன்றாத_வஞ்சித்தளை"),
    # பின்சீர் ஈற்றுச்சீர் ஆக இருக்கலாம்: நாள்/காசு நேர் முதல், மலர்/பிறப்பு நிரை முதல்
    ("தேமா",        "மலர்",         "இயற்சீர்_வெண்டளை"),
    ("தேமாங்காய்",  "நாள்",         "வெண்சீர்_வெண்டளை"),
    ("கூவிளம்",     "காசு",         "இயற்சீர்_வெண்டளை"),
    ("புளிமா",      "பிறப்பு",      "இயற்சீர்_வெண்டளை"),
])
def test_தளை_கொடு(முன்சீர், பின்சீர், எதிர்பார்ப்பு):
    assert தளை.தளை_கொடு(முன்சீர், பின்சீர்) == எதிர்பார்ப்பு


@pytest.mark.parametrize("பெயர், வெண்டளையா", [
    ("இயற்சீர்_வெண்டளை", True),
    ("வெண்சீர்_வெண்டளை", True),
    ("நேரொன்றாசிரியத்தளை", False),
    ("நிரையொன்றாசிரியத்தளை", False),
    ("கலித்தளை", False),
    ("ஒன்றிய_வஞ்சித்தளை", False),
    ("ஒன்றாத_வஞ்சித்தளை", False),
])
def test_வெண்டளையா(பெயர், வெண்டளையா):
    assert தளை.வெண்டளையா(பெயர்) is வெண்டளையா


@pytest.mark.parametrize("சீர், வகை", [
    ("தேமா", "மா"), ("புளிமா", "மா"),
    ("கருவிளம்", "விளம்"), ("கூவிளம்", "விளம்"),
    ("தேமாங்காய்", "காய்"), ("கூவிளங்காய்", "காய்"),
    ("புளிமாங்கனி", "கனி"), ("கருவிளங்கனி", "கனி"),
])
def test_சீர்வகை(சீர், வகை):
    assert தளை.சீர்வகை(சீர்) == வகை


@pytest.mark.parametrize("சீர், அசை", [
    ("தேமா", "நேர்"), ("கூவிளம்", "நேர்"), ("தேமாங்காய்", "நேர்"), ("கூவிளங்கனி", "நேர்"),
    ("புளிமா", "நிரை"), ("கருவிளம்", "நிரை"), ("புளிமாங்காய்", "நிரை"), ("கருவிளங்கனி", "நிரை"),
    ("நாள்", "நேர்"), ("காசு", "நேர்"), ("மலர்", "நிரை"), ("பிறப்பு", "நிரை"),
])
def test_முதலசை(சீர், அசை):
    assert தளை.முதலசை(சீர்) == அசை


def test_தெரியாத_சீர்_பிழை():
    with pytest.raises(ValueError):
        தளை.தளை_கொடு("தேமா", "இல்லாதசீர்")
    with pytest.raises(ValueError):
        தளை.தளை_கொடு("நாள்", "தேமா")     # ஈற்றுச்சீர் முன்சீராக வராது
