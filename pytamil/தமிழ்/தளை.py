# வெண்பா ஈற்றடியின் இறுதிச் சீர்கள்
ஈற்றுச்சீர்கள் = frozenset({'நாள்', 'மலர்', 'காசு', 'பிறப்பு'})

# நாலசைச்சீர்கள் (பொதுச்சீர்): ஈற்றசை நேர் (...பூ) அல்லது நிரை (...நிழல்).
# அனுமானம் (2026-09-20): தளை காணும்போது ...பூ சீர்களை காய்ச்சீர் போலவும் (ஈற்றசை நேர்),
# ...நிழல் சீர்களை கனிச்சீர் போலவும் (ஈற்றசை நிரை) கொள்கிறோம். இலக்கண நூல்கள் இதற்குத்
# தனி விதி தருவதில்லை; வெண்பாவில் இவை வராது என்பதே முதன்மை. மாற்ற வேண்டின் இங்கே.
