# -*- coding: utf-8 -*-
"""
இலக்கணம் — சொற்புணர்ச்சியின் எழுத்துநிலை விதிகள் (முழுமையடையாத கூறு).

தொடர்மொழி_ஆக்கு() இரு விதிகளை மட்டுமே அறியும்:

    தனிக்குறில் முன் நின்ற மெய் உயிர்வரின் இரட்டுதல்   ('கல்' + 'அது' -> 'கல்லது')
    மெய்யின் மேல் உயிர் வந்து ஒன்றுதல்                  ('மரம்' + 'அது' -> 'மரமது')

விதிகளை YAML-இல் வைக்கும் புணர்ச்சி.py-இன் வழியே முதன்மையானது; இது அவ்விதிகளை நேரடியாக
நிரலில் எழுதிப் பார்த்த முந்தைய முயற்சி. பிரம்மி எழுத்துமாற்றம், ஆண்டுவாரி பழைய எழுத்து
ஆகியவை இன்னும் எழுதப்படவில்லை (கீழே உள்ள NotImplementedError காண்க).
"""
from pytamil.தமிழ் import எழுத்து


def பிரம்மி(வாக்கியம்):
    """வாக்கியத்தைப் பிரம்மி எழுத்தாக மாற்று (இன்னும் எழுதப்படவில்லை)."""
    raise NotImplementedError("பிரம்மி எழுத்துமாற்றம் இன்னும் எழுதப்படவில்லை")

def பண்டைய_எழுத்து(வாக்கியம், வருடம்):
    """கொடுத்த ஆண்டில் வழங்கிய எழுத்து வடிவம் (இன்னும் எழுதப்படவில்லை)."""
    raise NotImplementedError("ஆண்டுவாரி எழுத்து வடிவம் இன்னும் எழுதப்படவில்லை")

def பண்டைய_சொல்(வாக்கியம், வருடம்):
    """கொடுத்த ஆண்டில் வழங்கிய சொல் வடிவம் (இன்னும் எழுதப்படவில்லை)."""
    raise NotImplementedError("ஆண்டுவாரி சொல் வடிவம் இன்னும் எழுதப்படவில்லை")

def பண்டைய_வாக்கியம்_ஆக்கு(வாக்கியம், வருடம்):
    """கொடுத்த ஆண்டில் வழங்கிய வாக்கிய வடிவம் (இன்னும் எழுதப்படவில்லை)."""
    raise NotImplementedError("ஆண்டுவாரி வாக்கிய வடிவம் இன்னும் எழுதப்படவில்லை")

def தனிமொழி_ஆக்கு(வாக்கியம்):
    """தொடர்மொழியைத் தனிமொழிகளாகப் பிரி (இன்னும் எழுதப்படவில்லை)."""
    raise NotImplementedError("தனிமொழி பிரித்தல் இன்னும் எழுதப்படவில்லை")


def தொடர்மொழி_ஆக்கு(நிலைமொழி, வருமொழி):
    """நிலைமொழியும் வருமொழியும் புணர்ந்த தொடர்மொழி; விதி பொருந்தாவிடின் 'அய்யொ'."""
    தொடர்மொழி = 'அய்யொ'
    நிலைமொழி_எழுத்துக்கள் = எழுத்து.எழுத்தாக்கு(நிலைமொழி)
    வருமொழி_எழுத்துக்கள் = எழுத்து.எழுத்தாக்கு(வருமொழி)

    # தனிக்குறில் முன் நின்ற மெய் உயிர்வரின் இரட்டுதல்
    # மெய் + எழுத்து = மெய்யெழுத்து
    if len(நிலைமொழி_எழுத்துக்கள்) == 2 and \
        எழுத்து.உயிர்மெய்_பிரி(நிலைமொழி_எழுத்துக்கள்[0])[1] in எழுத்து.குறில் and \
        எழுத்து.கடையெழுத்து(நிலைமொழி) in எழுத்து.மெய் and \
        எழுத்து.முதலெழுத்து(வருமொழி) in எழுத்து.உயிர்:
        தொடர்மொழி = தனிக்குறில்_முன்_நின்ற_மெய்_உயிர்வரின்_இரட்டுதல்(
            நிலைமொழி_எழுத்துக்கள், வருமொழி_எழுத்துக்கள்)

    # மெய்யின் மேல் உயிர் வந்து ஒன்றுதல்
    # உயிர் + எழுத்து = உயிரெழுத்து
    elif எழுத்து.கடையெழுத்து(நிலைமொழி) in எழுத்து.மெய் and \
         எழுத்து.முதலெழுத்து(வருமொழி) in எழுத்து.உயிர்:
        தொடர்மொழி = மெய்யின்_மேல்_உயிர்_வந்து_ஒன்றுதல்(
            நிலைமொழி_எழுத்துக்கள், வருமொழி_எழுத்துக்கள்)

    return தொடர்மொழி


def தனிக்குறில்_முன்_நின்ற_மெய்_உயிர்வரின்_இரட்டுதல்(நிலைமொழி_எழுத்துக்கள்,
                                                      வருமொழி_எழுத்துக்கள்):
    """'கல்' + 'அது' -> 'கல்லது': நிலைமொழியின் ஈற்று மெய் இரட்டித்து உயிரேற்கும்."""
    தொமொ = நிலைமொழி_எழுத்துக்கள் + \
           list(எழுத்து.உயிர்மெய்_ஆக்கு(நிலைமொழி_எழுத்துக்கள்[-1],
                                        வருமொழி_எழுத்துக்கள்[0])) + \
           வருமொழி_எழுத்துக்கள்[1:]

    return ''.join(தொமொ)


def மெய்யின்_மேல்_உயிர்_வந்து_ஒன்றுதல்(நிலைமொழி_எழுத்துக்கள், வருமொழி_எழுத்துக்கள்):
    """'மரம்' + 'அது' -> 'மரமது': நிலைமொழியின் ஈற்று மெய் வருமொழியின் உயிரேற்கும்."""
    தொமொ = நிலைமொழி_எழுத்துக்கள்[:-1] + \
           list(எழுத்து.உயிர்மெய்_ஆக்கு(நிலைமொழி_எழுத்துக்கள்[-1],
                                        வருமொழி_எழுத்துக்கள்[0])) + \
           வருமொழி_எழுத்துக்கள்[1:]

    return ''.join(தொமொ)
