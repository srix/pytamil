"""
எழுத்து — தமிழ் எழுத்துக்களின் வகைப்பாடும், எழுத்துநிலை அடிப்படைச் செயல்களும்.

எழுத்து வகைகள் (உயிர், மெய், வல்லினம், உயிர்மெய்க்குறில் ...) resources/எழுத்து.yaml-இல்
உள்ளன; இந்தக் கூறு அவற்றை ஏற்றி தொகுதி மாறிகளாகத் தருகிறது. எழுத்தை உடைத்தல்/சேர்த்தல்
Open-Tamil (tamil.utf8) வழி நடக்கிறது.

    எழுத்து.எழுத்தாக்கு('வணக்கம்')      # ['வ', 'ண', 'க', 'க', 'ம்'] போன்ற எழுத்துவரிசை
    எழுத்து.உயிர்மெய்விரி('வணக்கம்')    # மெய்யையும் உயிரையும் பிரித்த விரிவடிவம்
    எழுத்து.உயிர்மெய்சேர்(வரிசை)        # விரிவடிவத்தை மீண்டும் உயிர்மெய்யாகச் சேர்த்தல்
"""
import os

import yaml
